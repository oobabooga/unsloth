#!/usr/bin/env python3
"""gfx1151 Linux workflow: Studio main vs the baseline v0.44.0, image priority families x formats, with profiles.

  python diffusion_bench/amd/gen_prio8_img_workflow.py --out DIR --main-sha SHA --branch B \
      --job ID:GROUPS:ROLES:ARMS[:SETS] [--job ...] [--patch P] [--title T]

Each --job is one exclusive-GPU job (chained with needs + always(), so only one waits in the shared group):
  GROUPS  build_q5 groups, '+' separated (q21+q21t)
  ROLES   build_q5 roles per group, '+' separated, applied to every group (dit_bf16+te_bf16+vae+dit_int8+...)
  ARMS    spec tags, '+' separated, run in that order; 'tag@head' runs the head tree (main + --patch)
  SETS    extra run_cell --set KEY=JSON, '|' separated, for every arm (trial: width / height / steps)
Every arm: prof_cell.py (run_cell protocol + whole-cell memory monitor + one extra untimed profiled render), then
score.py (LPIPS vs each stack's own bf16 arm) and prio8_report.py. Measurement only: no secret, public repos only.
"""

from __future__ import annotations

import argparse
import shlex
from pathlib import Path

COMFY_TAG, COMFY_SHA = "v0.44.0", "2c75dc1b379a59e0880619d029607af5169a62ef"
