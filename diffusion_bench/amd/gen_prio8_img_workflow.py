KERNEL_STEP = '      - name: RDNA W8A8 kernels (oracle + bench on the head tree)\n        timeout-minutes: 60\n        run: |\n          set +e\n          K="$AMD_CI_WORK/out/kernel"; mkdir -p "$K"\n          HB="$AMD_CI_WORK/states/head/studio/backend"\n          "$AMD_CI_PY" -c "import triton; print(\'triton\', triton.__version__)"\n          timeout 1500 "$AMD_CI_PY" -u "$GITHUB_WORKSPACE/diffusion_bench/amd/w8a8_rdna_bench.py" --backend "$HB" --out "$K/bench.json" > "$K/bench.log" 2>&1\n          rc=$?; echo "bench rc=$rc"; tail -25 "$K/bench.log"\n          [ "$rc" -eq 3 ] && touch "$AMD_CI_WORK/out/SKIP_CELLS"\n          TILES=$("$AMD_CI_PY" -c "import json,sys; print(json.dumps(json.load(open(sys.argv[1])).get(\'chosen_cfg\', {}), separators=(\',\', \':\')))" "$K/bench.json" 2>/dev/null)\n          echo "bench winner tiles (not exported: cells run the shipped defaults) $TILES"\n          timeout 1500 "$AMD_CI_PY" -u "$GITHUB_WORKSPACE/diffusion_bench/amd/kernel_oracle.py" "$GITHUB_WORKSPACE/diffusion_bench/amd/studio_native_w8a8_rdna.py" \\\n            --spec-arg backend="$HB" --inductor-config emulate_precision_casts=True --out "$K/oracle" > "$K/oracle.log" 2>&1\n          echo "oracle rc=$?"; tail -40 "$K/oracle.log"\n          (cd "$HB" && timeout 600 "$AMD_CI_PY" -m pytest -q -p no:cacheprovider tests/test_diffusion_native_w8a8_rdna.py > "$K/pytest.log" 2>&1; echo "pytest rc=$?"; tail -5 "$K/pytest.log")\n          exit 0\n\n'


def _drop_step(text: str, prefix: str) -> str:
    """Remove the step starting at ``prefix`` up to the next step (Studio-only jobs)."""
    i = text.index(prefix)
    j = text.index("\n      - ", i + 1)
    return text[:i] + text[j + 1 :]


VAE_STEP = '      - name: VAE attention A/B (base tree vs half-math patch tree)\n        timeout-minutes: 45\n        run: |\n          set +e\n          export HF_HOME="$AMD_CI_WORK/hf_home" TORCH_HOME="$AMD_CI_WORK/torch_home" HF_HUB_DISABLE_TELEMETRY=1\n          unset HF_TOKEN HF_TOKEN_ORG\n          V="$AMD_CI_WORK/out/vae"; mkdir -p "$V"\n          git -C "$AMD_CI_WORK/repo" worktree add -q --detach "$AMD_CI_WORK/states/vae" "$BASE_SHA"\n          git -C "$AMD_CI_WORK/states/vae" apply --index "$GITHUB_WORKSPACE/amd_ci/patches/VAE_PATCH" || { echo "vae patch failed"; exit 0; }\n          IMG=$(find "$AMD_CI_WORK/runs" -name "*.png" -path "*f3*" 2>/dev/null | head -1)\n          echo "image: $IMG"\n          timeout 2400 "$AMD_CI_PY" -u "$GITHUB_WORKSPACE/diffusion_bench/amd/vae_attn_bench.py" --repo unsloth/flux-3-image-klein \\\n            --arm base="$AMD_CI_WORK/states/base" --arm half="$AMD_CI_WORK/states/vae" \\\n            --arm half_off="$AMD_CI_WORK/states/vae:UNSLOTH_VAE_ATTN_HALF_MATH=0" --image "$IMG" --out "$V/vae.json" > "$V/vae.log" 2>&1\n          echo "vae bench rc=$?"; tail -12 "$V/vae.log"\n          rm -f "$V"/*.pt\n          exit 0\n\n'


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required = True, type = Path)
    ap.add_argument("--main-sha", required = True)
    ap.add_argument("--branch", required = True)
    ap.add_argument("--job", action = "append", required = True)
    ap.add_argument("--patch", default = "nov5_marker.patch", help = "head patches, ',' separated, in order")
    ap.add_argument("--patch2", default = "", help = "second head tree (arms tag@head2): base patches + these, ',' separated")
    ap.add_argument("--base-patch", default = "", help = "patches on both trees, ',' separated")
    ap.add_argument("--kernel-step", action = "store_true", help = "RDNA W8A8 kernel oracle + bench before the cells")
    ap.add_argument("--vae-patch", default = "", help = "VAE attention A/B step after the cells with this patch")
    ap.add_argument("--studio-only", action = "store_true", help = "no baseline install or file build; Studio prefetch only")
    ap.add_argument("--cell-timeout", type = int, default = 3600)
    ap.add_argument("--budget-min", type = int, default = 200, help = "cells-step budget per job")
    ap.add_argument("--prof-step", type = int, default = 5)
    ap.add_argument("--shared-gpu", action = "store_true",
                    help = "correctness only (trial plumbing): no exclusive group; never quote its timings")
    args = ap.parse_args()
    text = HEADER.format(branch = args.branch, main_sha = args.main_sha, comfy_sha = COMFY_SHA, gguf_sha = GGUF_SHA)
    prev = None
    for spec in args.job:
        parts = spec.split(":")
        jid, groups, roles, arms = parts[:4]
        sets = parts[4] if len(parts) > 4 else ""
        arm_list = arms.split("+")
        studio = sorted({a.split("@")[0] for a in arm_list if "_s_" in a})
        if args.studio_only:
            if any("_c_" in a for a in arm_list):
                raise SystemExit("--studio-only takes Studio arms only")
            groups = ""
        # prefetch each distinct Studio load once (the repeat arm loads the same thing)
        prefetch = [t for t in studio if not t.endswith("_r")]
        comfy_arms = "rock default" if any(a.split("@")[0].endswith("_c_bf16d") for a in arm_list) else "rock"
        needs = f"    needs: [{prev}]\n    if: ${{{{ always() }}}}\n" if prev else ""
        set_args = " ".join(f"--set {shlex.quote(s)}" for s in sets.split("|") if s)
        text += JOB.format(jid = jid, title = f"{jid}: {', '.join(x.split('~')[0] for x in groups.split('+'))}", needs = needs,
                           timeout = args.budget_min + 330, comfy_tag = COMFY_TAG, patch = " ".join(args.patch.split(",")),
                           patch2 = " ".join(x for x in args.patch2.split(",") if x),
                           base_patches = " ".join(x for x in args.base_patch.split(",") if x),
                           kernel_step = KERNEL_STEP if args.kernel_step else "",
                           vae_step = VAE_STEP.replace("VAE_PATCH", args.vae_patch) if args.vae_patch else "",
                           comfy_arms = comfy_arms, groups = " ".join(x.replace("~", "~").replace("|", ",") for x in groups.split("+")), roles = roles.replace("+", ","),
                           prefetch = " ".join(prefetch), budget_s = args.budget_min * 60,
                           cells_timeout = args.budget_min + 70, arms = " ".join(arm_list), sets = set_args,
                           cell_timeout = args.cell_timeout, prof_step = args.prof_step)
        prev = jid
    if args.studio_only:
        text = _drop_step(text, "      - name: Baseline " + COMFY_TAG)
    if args.shared_gpu:
        text = text.replace("    concurrency:\n      group: amd-ci-gfx1151-gpu\n      cancel-in-progress: false\n", "")
        text = text.replace("exclusive GPU, prio8", "SHARED GPU: plumbing only, prio8")
    wf = args.out / ".github" / "workflows" / f"{args.branch}.yml"
    wf.parent.mkdir(parents = True, exist_ok = True)
    for old in wf.parent.glob("*.yml"):
        if old != wf:
            old.unlink()
    wf.write_text(text, encoding = "utf-8")
    print(f"wrote {wf}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
